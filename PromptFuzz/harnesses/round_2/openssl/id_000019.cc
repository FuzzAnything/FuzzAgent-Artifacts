    // Initialize OpenSSL if needed
    OpenSSL_add_all_algorithms();
    ERR_clear_error();
    
    // Create a FILE* from input data
    FILE *in_file = fmemopen((void *)data, size, "rb");
    if (!in_file) {
        assert_file_closed(&in_file);
	return 0;
    }
    
    // Create output file
    FILE *out_file = fopen("output_file", "wb");
    if (!out_file) {
        assert_file_closed(&in_file);;
        assert_file_closed(&out_file);
	assert_file_closed(&in_file);
	return 0;
    }
    
    // Get file descriptors
    int in_fd = fuzz_fileno(in_file);
    int out_fd = fuzz_fileno(out_file);
    
    // Create BIO chain for reading PKCS7 data
    BIO *bio_in = BIO_new_fp(in_file, BIO_NOCLOSE);
    BIO *bio_filter = BIO_new(BIO_f_md());
    BIO *bio_chain = BIO_push(bio_filter, bio_in);
    
    // Read PKCS7 structure from BIO
    PKCS7 *p7 = NULL;
    PKCS7 *p7_read = d2i_PKCS7_bio(bio_chain, &p7);
    
    // Create SSL_CTX for SSL operations
    SSL_CTX *ctx = SSL_CTX_new(TLS_method());
    if (ctx) {
        // Set certificate compression preference
        int comp_algs[] = {1, 2, 3};
        SSL_CTX_set1_cert_comp_preference(ctx, comp_algs, sizeof(comp_algs)/sizeof(comp_algs[0]));
        
        // Flush sessions
        SSL_CTX_flush_sessions_ex(ctx, time(NULL));
    }
    
    // Work with ASN1 types
    const ASN1_ITEM *attr_syntax = OSSL_ATTRIBUTES_SYNTAX_it();
    if (attr_syntax) {
        // Create and free ASN1_TYPE
        ASN1_TYPE *asn1_type = ASN1_TYPE_new();
        if (asn1_type) {
            ASN1_TYPE_free(asn1_type);
        }
    }
    
    // Work with OCSP responses
    struct stack_st_OCSP_RESPONSE *ocsp_stack = sk_OCSP_RESPONSE_new_null();
    if (ocsp_stack && size > 0) {
        // Create dummy OCSP_RESPONSE for testing
        OCSP_RESPONSE *ocsp_resp = OCSP_RESPONSE_new();
        if (ocsp_resp) {
            sk_OCSP_RESPONSE_push(ocsp_stack, ocsp_resp);
            
            // Find all occurrences (will be 1 since we just added it)
            int found_count = 0;
            sk_OCSP_RESPONSE_find_all(ocsp_stack, ocsp_resp, &found_count);
            
            // Clean up OCSP stack
            sk_OCSP_RESPONSE_pop_free(ocsp_stack, OCSP_RESPONSE_free);
        } else {
            sk_OCSP_RESPONSE_free(ocsp_stack);
        }
    }
    
    // Cleanup PKCS7 structure if read
    if (p7_read) {
        PKCS7_free(p7_read);
    }
    
    // Cleanup BIO chain
    BIO_free_all(bio_chain);  // This frees both bio_filter and bio_in
    
    // Cleanup SSL_CTX
    if (ctx) {
        SSL_CTX_free(ctx);
    }
    
    // Close files
    assert_file_closed(&in_file);;
    assert_file_closed(&out_file);;
    
    // Clean up output file
    remove("output_file");
    
    assert_file_closed(&out_file);
