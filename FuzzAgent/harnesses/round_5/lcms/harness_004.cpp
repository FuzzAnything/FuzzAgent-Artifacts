//   harness_000.cpp - profile parsing and basic transformations
//   harness_001.cpp - device link creation and virtual profiles  
//   harness_002.cpp - PostScript generation
//   harness_003.cpp - CGATS parsing and manipulation


// Helper function to create temporary cube file content based on fuzzer input
static std::string generate_cube_file_content(FuzzedDataProvider& fdp) {
    std::string cube_content;
    
    // Basic cube file header with configurable parameters
    cube_content += "# Cube file generated by fuzzer\n";
    cube_content += "TITLE \"Fuzzer Cube File\"\n";
    
    // Determine cube file type: 1D LUT, 3D LUT, or both
    uint8_t cube_type = fdp.ConsumeIntegral<uint8_t>() % 3;
    
    if (cube_type == 0 || cube_type == 2) {
        // 1D LUT configuration
        int lut1d_size = fdp.ConsumeIntegralInRange<int>(2, 65);
        cube_content += "LUT_1D_SIZE " + std::to_string(lut1d_size) + "\n";
        
        // Optional domain specification
        if (fdp.ConsumeBool()) {
            double min_r = fdp.ConsumeFloatingPointInRange<double>(0.0, 0.5);
            double min_g = fdp.ConsumeFloatingPointInRange<double>(0.0, 0.5);
            double min_b = fdp.ConsumeFloatingPointInRange<double>(0.0, 0.5);
            cube_content += "DOMAIN_MIN " + std::to_string(min_r) + " " + 
                                          std::to_string(min_g) + " " + 
                                          std::to_string(min_b) + "\n";
        }
        
        if (fdp.ConsumeBool()) {
            double max_r = fdp.ConsumeFloatingPointInRange<double>(0.5, 1.0);
            double max_g = fdp.ConsumeFloatingPointInRange<double>(0.5, 1.0);
            double max_b = fdp.ConsumeFloatingPointInRange<double>(0.5, 1.0);
            cube_content += "DOMAIN_MAX " + std::to_string(max_r) + " " + 
                                          std::to_string(max_g) + " " + 
                                          std::to_string(max_b) + "\n";
        }
        
        // 1D LUT data
        cube_content += "\n";
        for (int i = 0; i < lut1d_size; i++) {
            if (fdp.remaining_bytes() < 24) break;
            double r = fdp.ConsumeFloatingPointInRange<double>(0.0, 1.0);
            double g = fdp.ConsumeFloatingPointInRange<double>(0.0, 1.0);
            double b = fdp.ConsumeFloatingPointInRange<double>(0.0, 1.0);
            cube_content += std::to_string(r) + " " + std::to_string(g) + " " + std::to_string(b) + "\n";
        }
        cube_content += "\n";
    }
    
    if (cube_type == 1 || cube_type == 2) {
        // 3D LUT configuration
        int lut3d_size = fdp.ConsumeIntegralInRange<int>(2, 33);
        cube_content += "LUT_3D_SIZE " + std::to_string(lut3d_size) + "\n";
        
        // Optional domain specification if not already set
        if (cube_type == 1) {
            if (fdp.ConsumeBool()) {
                double min_r = fdp.ConsumeFloatingPointInRange<double>(0.0, 0.5);
                double min_g = fdp.ConsumeFloatingPointInRange<double>(0.0, 0.5);
                double min_b = fdp.ConsumeFloatingPointInRange<double>(0.0, 0.5);
                cube_content += "DOMAIN_MIN " + std::to_string(min_r) + " " + 
                                              std::to_string(min_g) + " " + 
                                              std::to_string(min_b) + "\n";
            }
            
            if (fdp.ConsumeBool()) {
                double max_r = fdp.ConsumeFloatingPointInRange<double>(0.5, 1.0);
                double max_g = fdp.ConsumeFloatingPointInRange<double>(0.5, 1.0);
                double max_b = fdp.ConsumeFloatingPointInRange<double>(0.5, 1.0);
                cube_content += "DOMAIN_MAX " + std::to_string(max_r) + " " + 
                                              std::to_string(max_g) + " " + 
                                              std::to_string(max_b) + "\n";
            }
        }
        
        // 3D LUT data
        cube_content += "\n";
        int total_entries = lut3d_size * lut3d_size * lut3d_size;
        for (int i = 0; i < total_entries; i++) {
            if (fdp.remaining_bytes() < 24) break;
            double r = fdp.ConsumeFloatingPointInRange<double>(0.0, 1.0);
            double g = fdp.ConsumeFloatingPointInRange<double>(0.0, 1.0);
            double b = fdp.ConsumeFloatingPointInRange<double>(0.0, 1.0);
            cube_content += std::to_string(r) + " " + std::to_string(g) + " " + std::to_string(b) + "\n";
        }
    }
    
    return cube_content;
}

int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
    // Minimum size check - need enough data for cube file generation
    if (size < 100) return 0;
    
    FuzzedDataProvider fdp(data, size);
    
    // Split input for different operations
    // 1. Consume parameters for cube file generation
    uint8_t test_variant = fdp.ConsumeIntegral<uint8_t>() % 4;
    
    // 2. Generate cube file content from fuzzer input
    std::string cube_content = generate_cube_file_content(fdp);
    if (cube_content.empty()) return 0;
    
    // 3. Create temporary file with cube content
    char temp_filename[] = "/tmp/cube_test_XXXXXX.cube";
    int fd = mkstemps(temp_filename, 5); // 5 for ".cube"
    if (fd < 0) return 0;
    
    FILE* temp_file = fdopen(fd, "w");
    if (!temp_file) {
        close(fd);
        return 0;
    }
    
    fwrite(cube_content.c_str(), 1, cube_content.size(), temp_file);
    fclose(temp_file);
    
    // 4. Create context for thread-safe functions
    cmsContext ctx = cmsCreateContext(NULL, NULL);
    if (ctx == NULL) {
        unlink(temp_filename);
        return 0;
    }
    
    // 5. Test cube file device link creation APIs based on variant
    cmsHPROFILE cube_profile = NULL;
    
    switch (test_variant) {
        case 0:
            // Test regular cube file device link creation
            cube_profile = cmsCreateDeviceLinkFromCubeFile(temp_filename);
            break;
            
        case 1:
            // Test thread-safe cube file device link creation
            cube_profile = cmsCreateDeviceLinkFromCubeFileTHR(ctx, temp_filename);
            break;
            
        case 2:
            // Test with file I/O APIs: open profile from file first
            {
                cmsHPROFILE file_profile = cmsOpenProfileFromFile(temp_filename, "r");
                if (file_profile) {
                    // Test save profile to stream
                    size_t stream_size = fdp.ConsumeIntegralInRange<size_t>(1024, 65536);
                    std::vector<uint8_t> stream_buffer = fdp.ConsumeBytes<uint8_t>(stream_size);
                    if (!stream_buffer.empty()) {
                        cmsIOHANDLER* io = cmsOpenIOhandlerFromMem(ctx, stream_buffer.data(), stream_buffer.size(), "w");
                        if (io) {
                            cmsSaveProfileToIOhandler(file_profile, io);
                            cmsCloseIOhandler(io);
                        }
                    }
                    
                    cmsCloseProfile(file_profile);
                }
                
                // Also test cube file device link
                cube_profile = cmsCreateDeviceLinkFromCubeFile(temp_filename);
            }
            break;
        case 3:
            // Test with stream-based profile opening
            {
                // Read cube file content into buffer
                FILE* read_file = fopen(temp_filename, "rb");
                if (read_file) {
                    fseek(read_file, 0, SEEK_END);
                    long file_size = ftell(read_file);
                    fseek(read_file, 0, SEEK_SET);
                    
                    if (file_size > 0 && file_size < 1048576) { // 1MB limit
                        std::vector<uint8_t> file_buffer(file_size);
                        fread(file_buffer.data(), 1, file_size, read_file);
                        // Test opening profile from IO handler
                        cmsIOHANDLER* read_io = cmsOpenIOhandlerFromMem(ctx, file_buffer.data(), file_size, "r");
                        if (read_io) {
                            cmsHPROFILE stream_profile = cmsOpenProfileFromIOhandlerTHR(ctx, read_io);
                            if (stream_profile) {
                                cmsCloseProfile(stream_profile);
                                // IO handler freed by cmsCloseProfile, don't call cmsCloseIOhandler
                            } else {
                                // cmsOpenProfileFromIOhandlerTHR already freed the IO handler on error
                                // Do NOT call cmsCloseIOhandler(read_io)
                            }
                        }
                    }
                    fclose(read_file);
                }
                
                // Test both regular and thread-safe cube file device link
                if (fdp.ConsumeBool()) {
                    cube_profile = cmsCreateDeviceLinkFromCubeFile(temp_filename);
                } else {
                    cube_profile = cmsCreateDeviceLinkFromCubeFileTHR(ctx, temp_filename);
                }
            }
            break;
    }
    
    // 6. If cube profile was created, exercise it
    if (cube_profile != NULL) {
        // Get basic profile information
        cmsUInt32Number header_flags = cmsGetHeaderFlags(cube_profile);
        cmsUInt32Number rendering_intent = cmsGetHeaderRenderingIntent(cube_profile);
        cmsColorSpaceSignature color_space = cmsGetColorSpace(cube_profile);
        cmsUInt32Number channels = cmsChannelsOf(color_space);
        
        // Create a simple transform to test the device link
        cmsHPROFILE srgb_profile = cmsCreate_sRGBProfile();
        if (srgb_profile != NULL) {
            cmsBool intent_supported = cmsIsIntentSupported(cube_profile, 
                                                          rendering_intent % 4, 
                                                          LCMS_USED_AS_INPUT);
            
            if (intent_supported) {
                cmsHTRANSFORM hTransform = cmsCreateTransform(cube_profile, 
                                                             TYPE_RGB_8, 
                                                             srgb_profile, 
                                                             TYPE_RGB_8,
                                                             rendering_intent % 4,
                                                             0);
                if (hTransform != NULL) {
                    // Apply transform with some test data
                    size_t test_data_size = fdp.ConsumeIntegralInRange<size_t>(3, 300);
                    std::vector<uint8_t> test_pixels = fdp.ConsumeBytes<uint8_t>(test_data_size);
                    
                    if (test_pixels.size() >= 3 && test_pixels.size() % 3 == 0) {
                        size_t num_pixels = test_pixels.size() / 3;
                        std::vector<uint8_t> output_pixels(test_pixels.size());
                        
                        cmsDoTransform(hTransform, test_pixels.data(), output_pixels.data(), num_pixels);
                    }
                    
                    cmsDeleteTransform(hTransform);
                }
            }
            
            cmsCloseProfile(srgb_profile);
        }
        
        cmsCloseProfile(cube_profile);
    }
    
    // 7. Cleanup
    cmsDeleteContext(ctx);
    unlink(temp_filename);
    
    return 0;
}

