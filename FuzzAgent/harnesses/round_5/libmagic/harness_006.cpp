// Helper class to generate magic files with specific types
class MagicFileGenerator {
public:
    MagicFileGenerator(FuzzedDataProvider& fdp) : fdp(fdp) {}
    
    std::string generate_magic_file() {
        std::string magic_content;
        
        // Add magic file header
        magic_content += "# Custom magic file generated by fuzzer\n";
        magic_content += "# This file contains diverse magic types to test apprentice_magic_strength_1\n";
        magic_content += "------------------------------------------------------------------------------\n\n";
        
        // Determine number of magic entries to generate
        size_t num_entries = fdp.ConsumeIntegralInRange<size_t>(1, 20);
        
        for (size_t i = 0; i < num_entries && fdp.remaining_bytes() > 10; i++) {
            magic_content += generate_magic_entry();
        }
        
        return magic_content;
    }
    
private:
    FuzzedDataProvider& fdp;
    
    std::string generate_magic_entry() {
        std::string entry;
        
        // Consume offset
        uint32_t offset = fdp.ConsumeIntegral<uint32_t>() % 1024;
        
        // Consume magic type
        MagicType type = static_cast<MagicType>(fdp.ConsumeIntegralInRange<int>(0, MAGIC_TYPE_COUNT - 1));
        
        // Consume value length
        size_t value_len = fdp.ConsumeIntegralInRange<size_t>(1, 256);
        
        // Start entry with offset
        entry += std::to_string(offset) + "\t";
        
        // Add type based on consumed value
        switch (type) {
            case FILE_BYTE:
                entry += "byte\t";
                entry += "=" + std::to_string(fdp.ConsumeIntegral<uint8_t>());
                break;
                
            case FILE_SHORT:
                entry += "short\t";
                entry += "=" + std::to_string(fdp.ConsumeIntegral<uint16_t>());
                break;
                
            case FILE_STRING:
                entry += "string\t";
                if (fdp.remaining_bytes() >= value_len) {
                    std::string str = fdp.ConsumeBytesAsString(value_len);
                    // Escape special characters
                    std::string escaped;
                    for (char c : str) {
                        if (c == '\\' || c == '\t') {
                            escaped += '\\';
                        }
                        escaped += c;
                    }
                    entry += escaped;
                } else {
                    entry += "test";
                }
                break;
                
            case FILE_PSTRING:
                entry += "pstring\t";
                entry += std::to_string(value_len) + "\t";
                if (fdp.remaining_bytes() >= value_len) {
                    std::string str = fdp.ConsumeBytesAsString(value_len);
                    entry += str;
                } else {
                    entry += "test";
                }
                break;
                
            case FILE_BESTRING16:
                entry += "bestring16\t";
                entry += std::to_string(value_len) + "\t";
                if (fdp.remaining_bytes() >= value_len * 2) {
                    std::string str = fdp.ConsumeBytesAsString(value_len * 2);
                    entry += str;
                } else {
                    entry += "4142"; // "AB" in hex
                }
                break;
                
            case FILE_LESTRING16:
                entry += "lestring16\t";
                entry += std::to_string(value_len) + "\t";
                if (fdp.remaining_bytes() >= value_len * 2) {
                    std::string str = fdp.ConsumeBytesAsString(value_len * 2);
                    entry += str;
                } else {
                    entry += "4142"; // "AB" in hex
                }
                break;
                
            case FILE_SEARCH:
                entry += "search/" + std::to_string(value_len) + "\t";
                if (fdp.remaining_bytes() >= value_len) {
                    std::string str = fdp.ConsumeBytesAsString(value_len);
                    entry += str;
                } else {
                    entry += "test";
                }
                break;
                
            case FILE_REGEX:
                entry += "regex\t";
                if (fdp.remaining_bytes() >= value_len) {
                    std::string str = fdp.ConsumeBytesAsString(value_len);
                    entry += str;
                } else {
                    entry += ".*";
                }
                break;
                
            case FILE_DEFAULT:
                entry += "default";
                break;
                
            case FILE_LONG:
                entry += "long\t";
                entry += "=" + std::to_string(fdp.ConsumeIntegral<uint32_t>());
                break;
                
            case FILE_FLOAT:
                entry += "float\t";
                entry += "=" + std::to_string(fdp.ConsumeFloatingPoint<float>());
                break;
                
            case FILE_DOUBLE:
                entry += "double\t";
                entry += "=" + std::to_string(fdp.ConsumeFloatingPoint<double>());
                break;
                
            case FILE_OCTAL:
                entry += "octal\t";
                entry += std::to_string(fdp.ConsumeIntegral<uint32_t>());
                break;
                
            case FILE_INDIRECT:
                entry += "indirect";
                if (fdp.ConsumeBool()) {
                    entry += "\t" + std::to_string(fdp.ConsumeIntegral<uint32_t>());
                }
                break;
                
            case FILE_NAME:
                entry += "name\t";
                entry += "test_file";
                break;
                
            case FILE_USE:
                entry += "use\t";
                entry += "test_magic";
                break;
                
            case FILE_GUID:
                entry += "guid\t";
                entry += "12345678-1234-1234-1234-123456789012";
                break;
                
            default:
                // For other types, use a simple byte test
                entry += "byte\t";
                entry += "=" + std::to_string(fdp.ConsumeIntegral<uint8_t>());
                break;
        }
        
        // Add description
        entry += "\t";
        if (fdp.remaining_bytes() > 10) {
            std::string desc = fdp.ConsumeRandomLengthString(50);
            // Replace newlines in description
            std::replace(desc.begin(), desc.end(), '\n', ' ');
            entry += desc;
        } else {
            entry += "test entry";
        }
        
        entry += "\n";
        
        // Sometimes add continuation lines (important for apprentice_magic_strength_1)
        if (fdp.ConsumeBool() && fdp.remaining_bytes() > 10) {
            size_t cont_level = fdp.ConsumeIntegralInRange<size_t>(1, 3);
            for (size_t j = 0; j < cont_level && fdp.remaining_bytes() > 10; j++) {
                entry += ">";
                for (size_t k = 0; k < j + 1; k++) {
                    entry += ">";
                }
                entry += " ";
                
                // Simple continuation with byte test
                entry += "byte\t=" + std::to_string(fdp.ConsumeIntegral<uint8_t>());
                entry += "\tcontinuation " + std::to_string(j + 1) + "\n";
            }
        }
        
        return entry;
    }
};

int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
    // Minimum input size check: need enough for basic operations
    if (size < 32) {
        return 0;
    }

    FuzzedDataProvider fdp(data, size);
    
    // Consume flags from input
    int flags = fdp.ConsumeIntegral<int>();
    
    // Limit flags to valid combinations for magic checking
    flags &= (MAGIC_DEBUG | MAGIC_SYMLINK | MAGIC_COMPRESS | MAGIC_DEVICES |
              MAGIC_MIME_TYPE | MAGIC_CONTINUE | MAGIC_CHECK | MAGIC_PRESERVE_ATIME |
              MAGIC_RAW | MAGIC_ERROR | MAGIC_MIME_ENCODING | MAGIC_APPLE |
              MAGIC_EXTENSION | MAGIC_COMPRESS_TRANSP | MAGIC_NO_COMPRESS_FORK);
    
    // Open magic handle with minimal flags to focus on strength calculation
    // MAGIC_NONE = 0, but we use flags from fuzzer input for variety
    magic_t magic = magic_open(flags);
    if (magic == nullptr) {
        return 0;  // Failed to open magic handle
    }
    
    // Try to load default magic database (required for magic_check to work properly)
    int load_result = magic_load(magic, nullptr);
    if (load_result == -1) {
        // If loading default fails, try to load from common paths
        const char* magic_paths[] = {"/etc/magic", "/usr/share/misc/magic"};
        for (const char* path : magic_paths) {
            load_result = magic_load(magic, path);
            if (load_result != -1) {
                break;
            }
        }
    }
    
    // If we still couldn't load magic database, create a minimal one
    if (load_result == -1 && fdp.remaining_bytes() > 100) {
        // Create a temporary minimal magic file
        char temp_filename[] = "/tmp/libmagic_strength_XXXXXX";
        int fd = mkstemp(temp_filename);
        if (fd >= 0) {
            // Write a minimal valid magic file
            const char* minimal_magic = 
                "0\tbyte\t0x00\ttest\n"
                "0\tstring\ttest\ttest\n";
            
            if (write(fd, minimal_magic, strlen(minimal_magic)) == (ssize_t)strlen(minimal_magic)) {
                fsync(fd);
                close(fd);
                
                // Try to load from temp file
                load_result = magic_load(magic, temp_filename);
                
                // Clean up temp file
                unlink(temp_filename);
            } else {
                close(fd);
                unlink(temp_filename);
            }
        }
    }
    
    // If database is loaded successfully, generate custom magic files and test
    if (load_result != -1 && fdp.remaining_bytes() > 50) {
        // Generate custom magic files with diverse types
        MagicFileGenerator generator(fdp);
        
        // Create temporary magic file with generated content
        char custom_magic_filename[] = "/tmp/libmagic_custom_XXXXXX";
        int custom_fd = mkstemp(custom_magic_filename);
        if (custom_fd >= 0) {
            // Generate magic file content with diverse types
            std::string magic_content = generator.generate_magic_file();
            
            if (write(custom_fd, magic_content.data(), magic_content.size()) == (ssize_t)magic_content.size()) {
                fsync(custom_fd);
                close(custom_fd);
                
                // Primary target: magic_check to trigger apprentice_magic_strength_1
                // This calls the chain: magic_check -> file_apprentice -> apprentice_1 -> 
                // apprentice_list -> file_magic_strength -> apprentice_magic_strength_1
                int check_result = magic_check(magic, custom_magic_filename);
                (void)check_result;  // Result can be -1 on error, which is fine for fuzzing
                
                // Secondary target: magic_compile to exercise compilation path
                // This also triggers strength calculations
                int compile_result = magic_compile(magic, custom_magic_filename);
                (void)compile_result;
                
                // Clean up custom magic file
                unlink(custom_magic_filename);
                
                // Test with multiple generated files if we have enough input
                if (fdp.remaining_bytes() > 100) {
                    // Create another magic file with different content
                    char second_magic_filename[] = "/tmp/libmagic_custom2_XXXXXX";
                    int second_fd = mkstemp(second_magic_filename);
                    if (second_fd >= 0) {
                        std::string second_content = generator.generate_magic_file();
                        
                        if (write(second_fd, second_content.data(), second_content.size()) == (ssize_t)second_content.size()) {
                            fsync(second_fd);
                            close(second_fd);
                            
                            // Test magic_check with second file
                            magic_check(magic, second_magic_filename);
                            
                            // Test magic_compile with second file
                            magic_compile(magic, second_magic_filename);
                            
                            unlink(second_magic_filename);
                        } else {
                            close(second_fd);
                            unlink(second_magic_filename);
                        }
                    }
                }
            } else {
                close(custom_fd);
                unlink(custom_magic_filename);
            }
        }
        
        // Also test with nullptr (check default database)
        magic_check(magic, nullptr);
        
        // Test compilation of default database
        magic_compile(magic, nullptr);
        
        // Test listing to exercise different paths
        magic_list(magic, nullptr);
    }
    
    // Clean up
    magic_close(magic);
    return 0;
}

