// Include libmagic header

// Magic file annotation types
#define ANNOTATION_APPLE 0
#define ANNOTATION_MIME  1
#define ANNOTATION_EXT   2
#define ANNOTATION_MIXED 3

// Helper function to generate magic file content with annotations
std::string generate_magic_file_with_annotations(FuzzedDataProvider& fdp, uint8_t annotation_type) {
    std::string magic_content;
    
    // Start with a magic file header comment
    magic_content += "# Magic file with annotations for fuzzing\n";
    magic_content += "# Generated by harness_020.cpp\n";
    magic_content += "# Target: parse_extra, parse_mime, parse_apple, parse_ext\n";
    magic_content += "----------------------------------------------------\n\n";
    
    // Generate some basic magic rules first
    size_t num_rules = fdp.ConsumeIntegralInRange<size_t>(1, 5);
    
    for (size_t rule_idx = 0; rule_idx < num_rules && fdp.remaining_bytes() > 0; rule_idx++) {
        // Generate offset
        uint32_t offset = fdp.ConsumeIntegral<uint32_t>() % 256;
        magic_content += std::to_string(offset) + "\t";
        
        // Choose data type
        uint8_t data_type = fdp.ConsumeIntegral<uint8_t>() % 6;
        switch (data_type) {
            case 0: {
                magic_content += "string\t";
                // Generate string value
                size_t str_len = fdp.ConsumeIntegralInRange<size_t>(1, 32);
                if (fdp.remaining_bytes() < str_len) {
                    str_len = fdp.remaining_bytes();
                }
                if (str_len > 0) {
                    std::vector<uint8_t> str_data = fdp.ConsumeBytes<uint8_t>(str_len);
                    magic_content += "\"";
                    for (size_t i = 0; i < str_data.size(); i++) {
                        if (str_data[i] >= 32 && str_data[i] < 127 && str_data[i] != '\\' && str_data[i] != '"') {
                            magic_content += static_cast<char>(str_data[i]);
                        } else {
                            magic_content += '.';
                        }
                    }
                    magic_content += "\"\t";
                }
                break;
            }
            case 1: {
                magic_content += "byte\t";
                // Generate byte value
                uint8_t byte_val = fdp.ConsumeIntegral<uint8_t>();
                char hex[5];
                snprintf(hex, sizeof(hex), "0x%02x", byte_val);
                magic_content += hex;
                magic_content += "\t";
                break;
            }
            case 2: {
                magic_content += "short\t";
                // Generate short value
                uint16_t short_val = fdp.ConsumeIntegral<uint16_t>();
                char hex_short[7];
                snprintf(hex_short, sizeof(hex_short), "0x%04x", short_val);
                magic_content += hex_short;
                magic_content += "\t";
                break;
            }
            case 3: {
                magic_content += "long\t";
                // Generate long value
                uint32_t long_val = fdp.ConsumeIntegral<uint32_t>();
                char hex_long[11];
                snprintf(hex_long, sizeof(hex_long), "0x%08x", long_val);
                magic_content += hex_long;
                magic_content += "\t";
                break;
            }
            case 4: {
                magic_content += "belong\t";
                // Generate belong value
                uint32_t belong_val = fdp.ConsumeIntegral<uint32_t>();
                char hex_belong[11];
                snprintf(hex_belong, sizeof(hex_belong), "0x%08x", belong_val);
                magic_content += hex_belong;
                magic_content += "\t";
                break;
            }
            case 5: {
                magic_content += "lelong\t";
                // Generate lelong value
                uint32_t lelong_val = fdp.ConsumeIntegral<uint32_t>();
                char hex_lelong[11];
                snprintf(hex_lelong, sizeof(hex_lelong), "0x%08x", lelong_val);
                magic_content += hex_lelong;
                magic_content += "\t";
                break;
            }
        }
        
        // Add description
        magic_content += "Test rule ";
        magic_content += std::to_string(rule_idx);
        magic_content += "\n";
        // Now add annotations based on type
        if (annotation_type == ANNOTATION_APPLE || annotation_type == ANNOTATION_MIXED) {
            // Add APPLE annotation (CREATOR/TYPE format)
            magic_content += "!:apple\t";
            
            // Generate Apple creator/type (4 chars each)
            std::string apple_creator;
            std::string apple_type;
            
            for (int i = 0; i < 4 && fdp.remaining_bytes() > 0; i++) {
                uint8_t c = fdp.ConsumeIntegral<uint8_t>();
                if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || 
                    (c >= '0' && c <= '9') || strchr("!+-./?", c)) {
                    apple_creator += static_cast<char>(c);
                } else {
                    apple_creator += 'A' + (c % 26);
                }
            }
            
            for (int i = 0; i < 4 && fdp.remaining_bytes() > 0; i++) {
                uint8_t c = fdp.ConsumeIntegral<uint8_t>();
                if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || 
                    (c >= '0' && c <= '9') || strchr("!+-./?", c)) {
                    apple_type += static_cast<char>(c);
                } else {
                    apple_type += 'A' + (c % 26);
                }
            }
            
            if (apple_creator.length() == 4 && apple_type.length() == 4) {
                magic_content += apple_creator;
                magic_content += " ";
                magic_content += apple_type;
                magic_content += "\n";
            }
        }
        
        if (annotation_type == ANNOTATION_MIME || annotation_type == ANNOTATION_MIXED) {
            // Add MIME annotation
            magic_content += "!:mime\t";
            
            // Generate MIME type (e.g., "text/plain", "application/octet-stream")
            size_t mime_len = fdp.ConsumeIntegralInRange<size_t>(5, 50);
            if (fdp.remaining_bytes() < mime_len) {
                mime_len = fdp.remaining_bytes();
            }
            
            if (mime_len > 0) {
                std::vector<uint8_t> mime_data = fdp.ConsumeBytes<uint8_t>(mime_len);
                std::string mime_str;
                for (size_t i = 0; i < mime_data.size(); i++) {
                    if ((mime_data[i] >= 'a' && mime_data[i] <= 'z') ||
                        (mime_data[i] >= 'A' && mime_data[i] <= 'Z') ||
                        (mime_data[i] >= '0' && mime_data[i] <= '9') ||
                        strchr("+-/.$?:{};=", mime_data[i])) {
                        mime_str += static_cast<char>(mime_data[i]);
                    } else if (mime_data[i] == ' ') {
                        // Replace space with slash for MIME type
                        mime_str += '/';
                    } else {
                        mime_str += 'a' + (mime_data[i] % 26);
                    }
                }
                
                // Ensure we have at least one slash
                if (mime_str.find('/') == std::string::npos) {
                    if (mime_str.length() > 4) {
                        mime_str.insert(mime_str.length() / 2, "/");
                    } else {
                        mime_str = "application/octet-stream";
                    }
                }
                
                magic_content += mime_str;
                magic_content += "\n";
            }
        }
        
        if (annotation_type == ANNOTATION_EXT || annotation_type == ANNOTATION_MIXED) {
            // Add EXTENSION annotation
            magic_content += "!:ext\t";
            
            // Generate file extensions (comma-separated list)
            size_t num_exts = fdp.ConsumeIntegralInRange<size_t>(1, 5);
            for (size_t ext_idx = 0; ext_idx < num_exts && fdp.remaining_bytes() > 0; ext_idx++) {
                if (ext_idx > 0) {
                    magic_content += ",";
                }
                
                // Generate extension (1-10 chars)
                size_t ext_len = fdp.ConsumeIntegralInRange<size_t>(1, 10);
                if (fdp.remaining_bytes() < ext_len) {
                    ext_len = fdp.remaining_bytes();
                }
                
                if (ext_len > 0) {
                    std::vector<uint8_t> ext_data = fdp.ConsumeBytes<uint8_t>(ext_len);
                    std::string ext_str;
                    for (size_t i = 0; i < ext_data.size(); i++) {
                        if ((ext_data[i] >= 'a' && ext_data[i] <= 'z') ||
                            (ext_data[i] >= 'A' && ext_data[i] <= 'Z') ||
                            (ext_data[i] >= '0' && ext_data[i] <= '9') ||
                            strchr(",!+-/@?_$&~.", ext_data[i])) {
                            ext_str += static_cast<char>(ext_data[i]);
                        } else {
                            ext_str += 'a' + (ext_data[i] % 26);
                        }
                    }
                    
                    // Ensure extension starts with a letter if empty
                    if (ext_str.empty()) {
                        ext_str = "txt";
                    }
                    
                    magic_content += ext_str;
                }
            }
            magic_content += "\n";
        }
        
        magic_content += "\n";
    }
    
    return magic_content;
}

int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
    // Minimum size check - need enough for basic magic file generation
    if (size < 64) {
        return 0;
    }
    
    FuzzedDataProvider fdp(data, size);
    
    // Consume flags for magic_open
    int flags = 0;
    
    // Consume a byte to determine which flags to set
    uint8_t flag_byte = fdp.ConsumeIntegral<uint8_t>();
    if (flag_byte & 0x01) flags |= MAGIC_DEBUG;
    if (flag_byte & 0x02) flags |= MAGIC_SYMLINK;
    if (flag_byte & 0x04) flags |= MAGIC_COMPRESS;
    if (flag_byte & 0x08) flags |= MAGIC_DEVICES;
    if (flag_byte & 0x10) flags |= MAGIC_MIME_TYPE;
    if (flag_byte & 0x20) flags |= MAGIC_CONTINUE;
    if (flag_byte & 0x40) flags |= MAGIC_CHECK;  // Important for annotation validation
    if (flag_byte & 0x80) flags |= MAGIC_RAW;
    
    // Open magic handle
    magic_t magic = magic_open(flags);
    if (magic == NULL) {
        return 0; // Failed to open magic handle
    }
    
    // Determine annotation type to test
    uint8_t annotation_type = fdp.ConsumeIntegral<uint8_t>() % 4;
    
    // Generate magic file content with annotations
    std::string magic_content = generate_magic_file_with_annotations(fdp, annotation_type);
    
    if (magic_content.empty()) {
        magic_close(magic);
        return 0;
    }
    
    // Create a temporary file with the magic content
    char temp_filename[] = "/tmp/libmagic_annot_XXXXXX";
    int fd = mkstemp(temp_filename);
    if (fd < 0) {
        magic_close(magic);
        return 0;
    }
    
    // Write magic content to temp file
    if (write(fd, magic_content.c_str(), magic_content.size()) != static_cast<ssize_t>(magic_content.size())) {
        close(fd);
        unlink(temp_filename);
        magic_close(magic);
        return 0;
    }
    close(fd);
    
    // Choose operation: 0 = magic_compile, 1 = magic_load_buffers
    uint8_t operation = fdp.ConsumeIntegral<uint8_t>() % 2;
    
    int result = -1;
    
    if (operation == 0) {
        // Test magic_compile - compile magic file with annotations
        result = magic_compile(magic, temp_filename);
    } else {
        // Test magic_load_buffers - load magic from buffer
        // Create buffer from magic content
        void* buffer = malloc(magic_content.size());
        if (buffer != NULL) {
            memcpy(buffer, magic_content.c_str(), magic_content.size());
            size_t buffer_size = magic_content.size();
            
            void* buffers[1] = {buffer};
            size_t sizes[1] = {buffer_size};
            
            result = magic_load_buffers(magic, buffers, sizes, 1);
            
            free(buffer);
        }
    }
    
    // If compilation/loading succeeded, test with some data
    if (result == 0) {
        // Generate some test data to use with the compiled magic
        size_t test_data_size = fdp.ConsumeIntegralInRange<size_t>(1, 1024);
        if (fdp.remaining_bytes() < test_data_size) {
            test_data_size = fdp.remaining_bytes();
        }
        
        if (test_data_size > 0) {
            std::vector<uint8_t> test_data = fdp.ConsumeBytes<uint8_t>(test_data_size);
            if (!test_data.empty()) {
                const char* magic_result = magic_buffer(magic, test_data.data(), test_data.size());
                (void)magic_result; // Result can be NULL, that's OK
            }
        }
    }
    
    // Clean up
    unlink(temp_filename);
    magic_close(magic);
    
    return 0;
}

