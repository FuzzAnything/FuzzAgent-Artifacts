/*
 * Fuzzing harness for libvpx targeting VP9 encoder configuration validation
 * Focus on exploring configuration parameter space to unblock 293+ branches in validate_config
 * and 359+ branches in vp9_pick_inter_mode
 * 
 * Target: HarnessAgent
 * Goal: Create a harness focused on vp9 encoder configuration space exploration to
 *       exercise validation logic and mode selection paths.
 * 
 * Specific blocked branches targeted:
 * - validate_config: 293 blocked branches (validation logic for encoder configuration)
 * - vp9_pick_inter_mode: 359 blocked branches (mode selection with different configs)
 * Total: 652+ blocked branches
 * 
 * APIs to target as specified in guidance:
 * - vpx_codec_enc_config_default (Required Helper: Config Setup)
 * - vpx_img_alloc (Required Helper: Buffer Management)
 * - vpx_codec_enc_init_ver (Required Helper: Encoder Init)
 * - vpx_codec_enc_config_set (Primary Target: Configuration Validation)
 * - vpx_codec_encode (Target: Encoding Execution)
 * - vpx_codec_get_cx_data (Required Helper: Data Retrieval)
 * - vpx_codec_destroy (Required Helper: Cleanup)
 * - vpx_img_free (Required Helper: Buffer Cleanup)
 * 
 * Invocation sequence from guidance:
 * 1. Call vpx_codec_enc_config_default to get default configuration
 * 2. Call vpx_img_alloc to create image buffers for input frames
 * 3. Call vpx_codec_enc_init_ver to initialize encoder with base configuration
 * 4. **Critical: Modify configuration parameters to test validation logic:**
 *    - Set max_gf_interval and min_gf_interval with various relationships (min > max, min = max, min < max)
 *    - Set g_lag_in_frames relative to max_gf_interval (both valid and invalid combinations)
 *    - Configure spatial (ss_number_layers) and temporal (ts_number_layers) scalability
 *    - Set different rate control modes (rc_end_usage: VPX_VBR, VPX_CBR, VPX_CQ, VPX_Q)
 *    - Enable/disable two-pass encoding (g_pass)
 *    - Set various cpu_used values (-9 to 9)
 * 5. Call vpx_codec_enc_config_set to apply modified configuration (triggers validate_config)
 * 6. Call vpx_codec_encode multiple times with different input data
 * 7. Call vpx_codec_get_cx_data to retrieve encoded output
 * 8. Call vpx_codec_destroy for cleanup
 * 9. Call vpx_img_free to release image buffers
 * 
 * Semantic differentiation from harness_015:
 * 1. Focuses specifically on configuration parameter space exploration (not SVC)
 * 2. Targets validate_config function (293 blocked branches) with edge case configurations
 * 3. Tests relationships between min_gf_interval, max_gf_interval, and g_lag_in_frames
 * 4. Explores different rate control modes (VBR, CBR, CQ, Q) and encoding passes
 * 5. Tests various cpu_used values (-9 to 9) for different speed-quality tradeoffs
 * 6. Simpler image buffer approach without complex SVC layer configurations
 * 
 * Reasoning from guidance: The 293+ blocked branches in validate_config function contain
 * complex conditional checks for encoder configuration validation. These conditions require
 * specific configuration parameter combinations that are not being generated by existing
 * harnesses. By systematically testing edge cases and valid/invalid combinations of
 * configuration parameters, we can exercise these blocked code paths. The subsequent
 * encoding calls will then trigger mode selection logic (vp9_pick_inter_mode) with the
 * configured parameters, potentially unblocking additional branches.
 */




int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
    // Minimum input size: need enough for configuration parameters and some frame data
    const size_t MIN_SIZE = sizeof(uint8_t) * 1024 + sizeof(int) * 64 + sizeof(unsigned int) * 64;
    if (size < MIN_SIZE) {
        return 0;
    }
    
    FuzzedDataProvider fdp(data, size);
    
    // Initialize encoder interface for VP9
    vpx_codec_iface_t* iface = vpx_codec_vp9_cx();
    if (!iface) {
        return 0;
    }
    
    vpx_codec_ctx_t codec;
    vpx_codec_enc_cfg_t cfg;
    
    // Step 1: Get default configuration
    if (vpx_codec_enc_config_default(iface, &cfg, 0) != VPX_CODEC_OK) {
        return 0;
    }
    
    // Step 2: Configure basic encoder parameters from fuzzer input
    // Use reasonable ranges for video dimensions
    cfg.g_w = fdp.ConsumeIntegralInRange<unsigned int>(16, 1920) & ~1; // Ensure even width
    cfg.g_h = fdp.ConsumeIntegralInRange<unsigned int>(16, 1080) & ~1; // Ensure even height
    
    // Set target bitrate and frame rate
    cfg.rc_target_bitrate = fdp.ConsumeIntegralInRange<unsigned int>(100, 5000); // kbps
    cfg.g_timebase.num = 1;
    cfg.g_timebase.den = fdp.ConsumeIntegralInRange<unsigned int>(24, 60); // fps
    
    // Step 3: Test keyframe interval relationships (critical for validate_config)
    // Consume values for min_kf_interval and max_kf_interval with various relationships
    unsigned int min_kf_interval = fdp.ConsumeIntegralInRange<unsigned int>(0, 32);
    unsigned int max_kf_interval = fdp.ConsumeIntegralInRange<unsigned int>(0, 32);
    
    // Apply different relationship patterns based on input
    uint8_t interval_relationship = fdp.ConsumeIntegral<uint8_t>() % 4;
    switch (interval_relationship) {
        case 0: // Normal case: min < max
            if (min_kf_interval >= max_kf_interval && max_kf_interval > 0) {
                min_kf_interval = max_kf_interval - 1;
            }
            break;
        case 1: // Edge case: min > max (should trigger validation error)
            if (min_kf_interval <= max_kf_interval && min_kf_interval > 0) {
                min_kf_interval = max_kf_interval + 1;
            }
            break;
        case 2: // Edge case: min == max
            min_kf_interval = max_kf_interval;
            break;
        case 3: // Edge case: zero values
            min_kf_interval = 0;
            max_kf_interval = 0;
            break;
    }
    
    cfg.kf_min_dist = min_kf_interval;
    cfg.kf_max_dist = max_kf_interval;
    
    // Step 4: Set g_lag_in_frames relative to max_kf_interval
    // This tests another validation condition in validate_config
    uint8_t lag_relationship = fdp.ConsumeIntegral<uint8_t>() % 3;
    switch (lag_relationship) {
        case 0: // Valid: lag <= max_kf_interval
            cfg.g_lag_in_frames = (max_kf_interval > 0) ? 
                fdp.ConsumeIntegralInRange<unsigned int>(0, max_kf_interval) : 0;
            break;
        case 1: // Edge case: lag > max_kf_interval (should trigger validation)
            cfg.g_lag_in_frames = max_kf_interval + 
                fdp.ConsumeIntegralInRange<unsigned int>(1, 10);
            break;
        case 2: // Zero lag (special case)
            cfg.g_lag_in_frames = 0;
            break;
    }
    
    // Step 5: Configure spatial and temporal scalability
    // Test different layer configurations
    cfg.ss_number_layers = fdp.ConsumeIntegralInRange<unsigned int>(1, 5);
    cfg.ts_number_layers = fdp.ConsumeIntegralInRange<unsigned int>(1, 5);
    
    // Set target bitrates for layers if configured
    if (cfg.ss_number_layers > 1) {
        for (unsigned int i = 0; i < cfg.ss_number_layers; i++) {
            cfg.ss_target_bitrate[i] = fdp.ConsumeIntegralInRange<unsigned int>(100, 1000);
        }
    }
    
    if (cfg.ts_number_layers > 1) {
        for (unsigned int i = 0; i < cfg.ts_number_layers; i++) {
            cfg.ts_target_bitrate[i] = fdp.ConsumeIntegralInRange<unsigned int>(100, 1000);
            cfg.ts_rate_decimator[i] = 1 << (i + 1); // Powers of 2: 2, 4, 8, 16, 32
        }
        cfg.ts_periodicity = cfg.ts_number_layers;
    }
    
    // Step 6: Set rate control mode (tests different code paths)
    uint8_t rc_mode = fdp.ConsumeIntegral<uint8_t>() % 4;
    switch (rc_mode) {
        case 0:
            cfg.rc_end_usage = VPX_VBR; // Variable Bit Rate
            break;
        case 1:
            cfg.rc_end_usage = VPX_CBR; // Constant Bit Rate
            break;
        case 2:
            cfg.rc_end_usage = VPX_CQ;  // Constrained Quality
            cfg.rc_min_quantizer = fdp.ConsumeIntegralInRange<unsigned int>(0, 63);
            cfg.rc_max_quantizer = fdp.ConsumeIntegralInRange<unsigned int>(cfg.rc_min_quantizer, 63);
            break;
        case 3:
            cfg.rc_end_usage = VPX_Q;   // Constant Quality
            break;
    }
    
    // Step 7: Set encoding pass mode
    uint8_t pass_mode = fdp.ConsumeIntegral<uint8_t>() % 3;
    switch (pass_mode) {
        case 0:
            cfg.g_pass = VPX_RC_ONE_PASS;
            break;
        case 1:
            cfg.g_pass = VPX_RC_FIRST_PASS;
            break;
        case 2:
            cfg.g_pass = VPX_RC_LAST_PASS;
            // For two-pass encoding, need to set some two-pass specific parameters
            cfg.rc_twopass_stats_in.buf = nullptr;
            cfg.rc_twopass_stats_in.sz = 0;
            break;
    }
    
    // Step 8: Set cpu_used value (-9 to 9 range)
    // Negative values are best quality, positive values are faster encoding
    cfg.g_usage = 0; // Ensure this is zero as required
    int cpu_used = fdp.ConsumeIntegralInRange<int>(-9, 9);
    
    // Step 9: Allocate image buffer for input frames
    vpx_image_t* img = vpx_img_alloc(nullptr, VPX_IMG_FMT_I420, cfg.g_w, cfg.g_h, 1);
    if (!img) {
        return 0;
    }
    
    // Fill image buffer with fuzzer data
    size_t y_size = cfg.g_w * cfg.g_h;
    size_t uv_size = ((cfg.g_w + 1) / 2) * ((cfg.g_h + 1) / 2);
    
    if (fdp.remaining_bytes() < y_size + 2 * uv_size) {
        vpx_img_free(img);
        return 0;
    }
    
    // Consume YUV data for the image
    std::vector<uint8_t> y_data = fdp.ConsumeBytes<uint8_t>(y_size);
    std::vector<uint8_t> u_data = fdp.ConsumeBytes<uint8_t>(uv_size);
    std::vector<uint8_t> v_data = fdp.ConsumeBytes<uint8_t>(uv_size);
    
    memcpy(img->planes[VPX_PLANE_Y], y_data.data(), y_size);
    memcpy(img->planes[VPX_PLANE_U], u_data.data(), uv_size);
    memcpy(img->planes[VPX_PLANE_V], v_data.data(), uv_size);
    
    // Step 10: Initialize encoder with base configuration
    vpx_codec_flags_t flags = 0;
    if (vpx_codec_enc_init_ver(&codec, iface, &cfg, flags, VPX_ENCODER_ABI_VERSION) != VPX_CODEC_OK) {
        vpx_img_free(img);
        return 0;
    }
    
    // Step 11: Set cpu_used parameter
    vpx_codec_control(&codec, VP8E_SET_CPUUSED, cpu_used);
    
    // Step 12: Try to apply configuration changes (triggers validate_config)
    // Note: vpx_codec_enc_config_set will call validate_config internally
    vpx_codec_err_t config_result = vpx_codec_enc_config_set(&codec, &cfg);
    // We don't fail if config_set fails - invalid configurations are what we want to test
    
    // Step 13: Encode multiple frames to exercise mode selection
    // Use different frame flags to test various encoding paths
    int num_frames = fdp.ConsumeIntegralInRange<int>(1, 5);
    for (int i = 0; i < num_frames; i++) {
        vpx_enc_frame_flags_t frame_flags = 0;
        
        // Set frame flags based on input
        if (fdp.ConsumeBool()) {
            frame_flags |= VPX_EFLAG_FORCE_KF;
        }
        
        // Encode the frame
        if (vpx_codec_encode(&codec, img, i, 1, frame_flags, VPX_DL_REALTIME) != VPX_CODEC_OK) {
            // Encoding failure is acceptable - we're testing edge cases
            break;
        }
        
        // Retrieve encoded data
        const vpx_codec_cx_pkt_t* pkt = nullptr;
        vpx_codec_iter_t iter = nullptr;
        while ((pkt = vpx_codec_get_cx_data(&codec, &iter)) != nullptr) {
            // Process packet if needed
            if (pkt->kind == VPX_CODEC_CX_FRAME_PKT) {
                // Frame packet received
            }
        }
        
        // Check if we have enough input remaining for another iteration
        if (fdp.remaining_bytes() < 100) {
            break;
        }
    }
    
    // Step 14: Cleanup
    vpx_codec_destroy(&codec);
    vpx_img_free(img);
    
    return 0;
}

