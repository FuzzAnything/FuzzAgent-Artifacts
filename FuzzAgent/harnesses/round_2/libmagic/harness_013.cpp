// Create a temporary file with fuzzer data
class TemporaryFile {
public:
    TemporaryFile(const uint8_t* data, size_t size) {
        char filename[] = "/tmp/magic_fuzz_XXXXXX";
        fd = mkstemp(filename);
        if (fd < 0) {
            return;
        }
        
        strncpy(path, filename, sizeof(path) - 1);
        path[sizeof(path) - 1] = '\0';
        
        ssize_t written = write(fd, data, size);
        if (written < 0) {
            close(fd);
            fd = -1;
            unlink(path);
            path[0] = '\0';
            return;
        }
        
        close(fd);
        fd = -1;
    }
    
    ~TemporaryFile() {
        if (path[0] != '\0') {
            unlink(path);
        }
    }
    
    const char* getPath() const { return path[0] != '\0' ? path : nullptr; }
    
private:
    char path[256] = {0};
    int fd = -1;
};

