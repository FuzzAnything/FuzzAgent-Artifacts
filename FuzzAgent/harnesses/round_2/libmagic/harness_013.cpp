// Generate a simple magic database for testing
std::string generate_test_magic_rules(FuzzedDataProvider& fdp) {
    std::string rules;
    
    // Add a header comment
    rules = "# Test magic database generated by fuzzer\n";
    
    // Add some basic rules based on fuzzer input
    int num_rules = fdp.ConsumeIntegralInRange<int>(1, 10);
    
    for (int i = 0; i < num_rules; i++) {
        int rule_type = fdp.ConsumeIntegralInRange<int>(0, 3);
        
        switch (rule_type) {
            case 0:
                // String match rule
                rules += "0 string ";
                rules += fdp.ConsumeRandomLengthString(16);
                rules += " Test file type ";
                rules += std::to_string(i);
                rules += "\n";
                break;
                
            case 1:
                // Byte match rule
                rules += "0 byte ";
                rules += std::to_string(fdp.ConsumeIntegralInRange<int>(0, 255));
                rules += " Byte test ";
                rules += std::to_string(i);
                rules += "\n";
                break;
                
            case 2:
                // Short match rule
                rules += "0 beshort ";
                rules += std::to_string(fdp.ConsumeIntegralInRange<int>(0, 65535));
                rules += " Short test ";
                rules += std::to_string(i);
                rules += "\n";
                break;
                
            case 3:
                // Long match rule
                rules += "0 belong ";
                rules += std::to_string(fdp.ConsumeIntegral<uint32_t>());
                rules += " Long test ";
                rules += std::to_string(i);
                rules += "\n";
                break;
        }
    }
    
    return rules;
}

int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
    if (size < 8) {
        // Need minimum data for meaningful testing
        return 0;
    }
    
    FuzzedDataProvider fdp(data, size);
    
    // Consume test configuration from fuzzer input
    int test_mode = fdp.ConsumeIntegralInRange<int>(0, 7);
    int flags = fdp.ConsumeIntegral<int>();
    
    // Mask flags to valid values
    flags &= (MAGIC_DEBUG | MAGIC_SYMLINK | MAGIC_COMPRESS | MAGIC_DEVICES |
              MAGIC_MIME_TYPE | MAGIC_CONTINUE | MAGIC_CHECK | 
              MAGIC_PRESERVE_ATIME | MAGIC_RAW | MAGIC_ERROR | 
              MAGIC_MIME_ENCODING | MAGIC_APPLE | MAGIC_EXTENSION);
    
    // Initialize magic cookie
    magic_t magic = magic_open(flags);
    if (magic == NULL) {
        return 0;
    }
    
    try {
        switch (test_mode) {
            case 0: {
                // Test 1: Buffer operations with various data patterns
                // This exercises buffer.c internally
                size_t buffer_size = fdp.ConsumeIntegralInRange<size_t>(0, 4096);
                std::vector<uint8_t> buffer_data = fdp.ConsumeBytes<uint8_t>(buffer_size);
                
                if (!buffer_data.empty()) {
                    const char* result = magic_buffer(magic, buffer_data.data(), buffer_data.size());
                    (void)result; // Use result to avoid unused variable warning
                }
                break;
            }
            
            case 1: {
                // Test 2: File operations with temporary file
                // This exercises file.c and pread.c internally
                size_t file_size = fdp.ConsumeIntegralInRange<size_t>(1, 2048);
                std::vector<uint8_t> file_data = fdp.ConsumeBytes<uint8_t>(file_size);
                
                if (!file_data.empty()) {
                    TemporaryFile tmp_file(file_data.data(), file_data.size());
                    if (tmp_file.getPath()) {
                        const char* result = magic_file(magic, tmp_file.getPath());
                        (void)result;
                    }
                }
                break;
            }
            
            case 2: {
                // Test 3: Magic database loading and compilation
                // This exercises string utilities and formatting functions
                std::string magic_rules = generate_test_magic_rules(fdp);
                TemporaryMagicDB tmp_db(reinterpret_cast<const uint8_t*>(magic_rules.c_str()), 
                                        magic_rules.size());
                
                if (tmp_db.getPath()) {
                    // Try to load the magic database
                    magic_load(magic, tmp_db.getPath());
                    
                    // Try to compile it
                    magic_compile(magic, tmp_db.getPath());
                    
                    // Try to check it
                    magic_check(magic, tmp_db.getPath());
                    
                    // Try to list it
                    magic_list(magic, tmp_db.getPath());
                }
                break;
            }
            
            case 3: {
                // Test 4: Error handling and edge cases
                // This exercises error formatting functions
                
                // Test with NULL buffer
                const char* result = magic_buffer(magic, NULL, 0);
                (void)result;
                
                // Get error information
                const char* error_msg = magic_error(magic);
                (void)error_msg;
                
                int err = magic_errno(magic);
                (void)err;
                
                // Test flag manipulation
                int current_flags = magic_getflags(magic);
                int new_flags = flags & (MAGIC_DEBUG | MAGIC_SYMLINK | MAGIC_COMPRESS | 
                                        MAGIC_DEVICES | MAGIC_MIME_TYPE | MAGIC_CONTINUE);
                magic_setflags(magic, new_flags);
                
                // Test with some data
                size_t buffer_size = fdp.ConsumeIntegralInRange<size_t>(0, 512);
                std::vector<uint8_t> buffer_data = fdp.ConsumeBytes<uint8_t>(buffer_size);
                
                if (!buffer_data.empty()) {
                    result = magic_buffer(magic, buffer_data.data(), buffer_data.size());
                    (void)result;
                }
                
                // Restore flags
                magic_setflags(magic, current_flags);
                break;
            }
            
            case 4: {
                // Test 5: Multiple operations with different flags
                // This exercises various internal utility code paths
                
                // Test with MIME type detection
                int mime_flags = flags | MAGIC_MIME_TYPE;
                magic_setflags(magic, mime_flags);
                
                size_t buffer_size = fdp.ConsumeIntegralInRange<size_t>(0, 1024);
                std::vector<uint8_t> buffer_data = fdp.ConsumeBytes<uint8_t>(buffer_size);
                
                if (!buffer_data.empty()) {
                    const char* result = magic_buffer(magic, buffer_data.data(), buffer_data.size());
                    (void)result;
                }
                
                // Test with MIME encoding detection
                int mime_encoding_flags = flags | MAGIC_MIME_ENCODING;
                magic_setflags(magic, mime_encoding_flags);
                
                if (!buffer_data.empty()) {
                    const char* result = magic_buffer(magic, buffer_data.data(), buffer_data.size());
                    (void)result;
                }
                
                // Test with Apple type detection
                int apple_flags = flags | MAGIC_APPLE;
                magic_setflags(magic, apple_flags);
                
                if (!buffer_data.empty()) {
                    const char* result = magic_buffer(magic, buffer_data.data(), buffer_data.size());
                    (void)result;
                }
                
                // Restore original flags
                magic_setflags(magic, flags);
                break;
            }
            
            case 5: {
                // Test 6: Large buffer operations
                // This exercises buffer handling with large sizes
                size_t buffer_size = fdp.ConsumeIntegralInRange<size_t>(1024, 8192);
                if (buffer_size > fdp.remaining_bytes()) {
                    buffer_size = fdp.remaining_bytes();
                }
                
                std::vector<uint8_t> buffer_data = fdp.ConsumeBytes<uint8_t>(buffer_size);
                
                if (!buffer_data.empty()) {
                    // Test with various chunk sizes
                    for (size_t chunk_size = 1; chunk_size <= 4 && chunk_size <= buffer_data.size(); chunk_size++) {
                        const char* result = magic_buffer(magic, buffer_data.data(), chunk_size);
                        (void)result;
                    }
                    
                    // Test with full buffer
                    const char* result = magic_buffer(magic, buffer_data.data(), buffer_data.size());
                    (void)result;
                }
                break;
            }
            
            case 6: {
                // Test 7: Empty and minimal data tests
                // This exercises edge case handling
                
                // Test with empty buffer
                const char* result = magic_buffer(magic, NULL, 0);
                (void)result;
                
                // Test with 1-byte buffer
                if (fdp.remaining_bytes() >= 1) {
                    uint8_t single_byte = fdp.ConsumeIntegral<uint8_t>();
                    result = magic_buffer(magic, &single_byte, 1);
                    (void)result;
                }
                
                // Test with 2-byte buffer
                if (fdp.remaining_bytes() >= 2) {
                    std::vector<uint8_t> two_bytes = fdp.ConsumeBytes<uint8_t>(2);
                    result = magic_buffer(magic, two_bytes.data(), 2);
                    (void)result;
                }
                break;
            }
            
            case 7: {
                // Test 8: Comprehensive mixed testing
                // Combine multiple approaches
                
                // First test buffer operations
                size_t buffer_size = fdp.ConsumeIntegralInRange<size_t>(0, 2048);
                std::vector<uint8_t> buffer_data = fdp.ConsumeBytes<uint8_t>(buffer_size);
                
                if (!buffer_data.empty()) {
                    const char* result = magic_buffer(magic, buffer_data.data(), buffer_data.size());
                    (void)result;
                }
                
                // Then test file operations if we have enough data
                if (fdp.remaining_bytes() >= 16) {
                    size_t file_size = fdp.ConsumeIntegralInRange<size_t>(1, 1024);
                    std::vector<uint8_t> file_data = fdp.ConsumeBytes<uint8_t>(file_size);
                    
                    if (!file_data.empty()) {
                        TemporaryFile tmp_file(file_data.data(), file_data.size());
                        if (tmp_file.getPath()) {
                            const char* result = magic_file(magic, tmp_file.getPath());
                            (void)result;
                        }
                    }
                }
                
                // Test error APIs
                const char* error_msg = magic_error(magic);
                (void)error_msg;
                
                int err = magic_errno(magic);
                (void)err;
                break;
            }
        }
    } catch (...) {
        // Catch any exceptions from FuzzedDataProvider
    }
    
    // Clean up
    magic_close(magic);
    
    return 0;
}

